#!/usr/bin/env python3
"""Analysis of the mReasoner references generated from Lisp.

Usage:
  python3 sbcl/tests/compare.py report
      Reads outputs/mreasoner-s<N>.json, checks determinism across seeds,
      divergences from the predictions stored in Diagnostics.lisp and errors,
      compares with outputs/mreasoner-fixed-s1.json if present, and writes
      sbcl/tests/REPORT.md.

  python3 sbcl/tests/compare.py verify REFERENCE.json CANDIDATE.json
      Compares two outputs case by case (for example, before and after a
      change to mReasoner). Exits with code 1 if any case differs.

Standard library only.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUTS = HERE / "outputs"


def load_runs():
    files = sorted(OUTPUTS.glob("mreasoner-s*.json"))
    return [(f.stem.split("-s")[-1], json.loads(f.read_text(encoding="utf-8"))) for f in files]


def sections(doc):
    return {k: v for k, v in doc.items() if isinstance(v, list) and v and isinstance(v[0], dict) and "id" in v[0]}


def varying_cases(runs):
    """Ids of the cases whose content changes across seeds, per section."""
    base = sections(runs[0][1])
    result = {}
    for section, cases in base.items():
        varying = []
        for i, case in enumerate(cases):
            for _, other in runs[1:]:
                if sections(other)[section][i] != case:
                    varying.append(case["id"])
                    break
        result[section] = (len(cases), varying)
    return result


def has_error(value):
    if isinstance(value, dict):
        if value.get("error"):
            return True
        return any(has_error(v) for v in value.values())
    if isinstance(value, str):
        return value.startswith("ERROR")
    if isinstance(value, list):
        return any(has_error(v) for v in value)
    return False


def report():
    runs = load_runs()
    if not runs:
        print("No outputs found; run sbcl/tests/generate.sh first.")
        return
    doc = runs[0][1]
    seeds = ", ".join(s for s, _ in runs)
    lines = ["# mReasoner reference report", "",
             "Generated by `sbcl/tests/compare.py report` from `sbcl/tests/outputs/`.",
             "Do not edit by hand: regenerate with `sbcl/tests/generate.sh`.", "",
             f"Program: {doc.get('program')}. Implementation: {doc.get('implementation')}. Seeds: {seeds}.", ""]

    lines += ["## Determinism across seeds", "", "| Section | Cases | Vary across seeds |", "| --- | --- | --- |"]
    for section, (n, var) in varying_cases(runs).items():
        lines.append(f"| {section} | {n} | {len(var)}{': ' + ', '.join(var) if var else ''} |")
    lines.append("")

    divergent, errors = [], []
    for section, cases in sections(doc).items():
        for case in cases:
            if has_error(case):
                errors.append(case["id"])
            if case.get("matches_stored") is False:
                divergent.append((section, case))
            for sub in ("omega_0", "omega_1"):
                if isinstance(case.get(sub), dict) and case[sub].get("matches_stored") is False:
                    divergent.append((f"{section} ({sub})", case))

    lines += ["## Divergences from the predictions stored in Diagnostics.lisp", ""]
    if not divergent:
        lines += ["None.", ""]
    else:
        lines += ["| Section | Case | Stored prediction | Obtained |", "| --- | --- | --- | --- |"]
        for section, case in divergent:
            if "omega" in section:
                sub = section.split("(")[1].rstrip(")")
                expected, obtained = case.get("stored_2011"), case[sub].get("prediction")
                name = f"{case['id']} {' '.join(case['premises'])}"
            elif "stored" in case:
                expected = case["stored"]
                obtained = [case.get("necessary"), case.get("possible")]
                name = f"{case['id']} {case.get('premise')} / {case.get('conclusion')}"
            else:
                expected, obtained = case.get("stored_2012"), case.get("system2")
                name = f"{case['id']} {' '.join(case['premises'])}"
            lines.append(f"| {section} | {name} | {expected} | {obtained} |")
        lines.append("")

    lines += ["## Cases with an error", "", ", ".join(errors) if errors else "None.", ""]
    lines += effect_of_fixes()
    (HERE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Written {HERE / 'REPORT.md'}")


def differences(ref, cand):
    """List of (section, id, keys that change) between two outputs with the same structure."""
    out = []
    for section, cases in sections(ref).items():
        others = {c["id"]: c for c in cand.get(section, [])}
        for case in cases:
            other = others.get(case["id"])
            if other is None:
                out.append((section, case["id"], ["(missing)"]))
            elif other != case:
                out.append((section, case["id"], sorted(k for k in case if case.get(k) != other.get(k))))
        new = [c["id"] for c in cand.get(section, []) if c["id"] not in {x["id"] for x in cases}]
        out += [(section, n, ["(new)"]) for n in new]
    return out


def effect_of_fixes():
    base = OUTPUTS / "mreasoner-s1.json"
    fixed = OUTPUTS / "mreasoner-fixed-s1.json"
    if not (base.exists() and fixed.exists()):
        return []
    ref = json.loads(base.read_text(encoding="utf-8"))
    cand = json.loads(fixed.read_text(encoding="utf-8"))
    diffs = differences(ref, cand)
    lines = ["## Effect of the proposed fixes", "",
             "Compares `mreasoner-s1.json` (original) with `mreasoner-fixed-s1.json` "
             "(original + `sbcl/proposed-fixes.lisp`).", ""]
    if not diffs:
        return lines + ["No changes.", ""]
    lines += ["| Section | Case | Fields that change |", "| --- | --- | --- |"]
    lines += [f"| {s} | {i} | {', '.join(k)} |" for s, i, k in diffs]
    return lines + ["", f"Total: {len(diffs)} case(s) change; the rest are identical.", ""]


def verify(ref_path, cand_path):
    ref = json.loads(Path(ref_path).read_text(encoding="utf-8"))
    cand = json.loads(Path(cand_path).read_text(encoding="utf-8"))
    diffs = differences(ref, cand)
    for section, case_id, keys in diffs:
        print(f"DIFFERS {section}/{case_id}: {', '.join(keys)}")
    print(f"{len(diffs)} difference(s).")
    return 1 if diffs else 0


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "report":
        report()
    elif len(sys.argv) == 4 and sys.argv[1] == "verify":
        sys.exit(verify(sys.argv[2], sys.argv[3]))
    else:
        print(__doc__)
        sys.exit(2)
